// Writes src/d2-pin.ts from the @d2lang/d2 entry in pnpm-lock.yaml; the
// first step of `pnpm build`. The action downloads D2 at run time (it is too
// large to bundle), so the version and checksum it trusts come from the
// lockfile: upgrading the @d2lang/d2 devDependency and rebuilding is all it
// takes, like any other dependency.
import { existsSync, readFileSync, writeFileSync } from "node:fs"

export function lockfilePin(lockfile) {
  const m = /\n {2}'@d2lang\/d2@([^']+)':\n {4}resolution: \{integrity: (sha512-[^}\s]+)\}/.exec(
    lockfile,
  )
  if (!m) throw new Error("No @d2lang/d2 resolution in pnpm-lock.yaml")
  const [, version, integrity] = m
  return {
    version,
    tarball: `https://registry.npmjs.org/@d2lang/d2/-/d2-${version}.tgz`,
    integrity,
  }
}

export function pinSource(pin) {
  return `// Generated by \`pnpm build\` from pnpm-lock.yaml; do not edit by hand.

/** The D2.js release the action downloads, and the checksum it must match. */
export const D2_PIN = {
  version: "${pin.version}",
  tarball: "${pin.tarball}",
  integrity:
    "${pin.integrity}",
} as const
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const root = new URL("../", import.meta.url)
  const pin = lockfilePin(readFileSync(new URL("pnpm-lock.yaml", root), "utf8"))
  const target = new URL("src/d2-pin.ts", root)
  const source = pinSource(pin)
  if (!existsSync(target) || readFileSync(target, "utf8") !== source) {
    writeFileSync(target, source)
    console.log(`src/d2-pin.ts: pinned @d2lang/d2 ${pin.version}`)
  }
}
