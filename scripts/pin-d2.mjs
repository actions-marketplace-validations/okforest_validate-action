// Writes src/d2-pin.ts from the @d2lang/d2 entry in pnpm-lock.yaml. The
// action downloads D2 at run time (it is too large to bundle), so the version
// and checksum it trusts come from the lockfile: bump the devDependency in
// pnpm-workspace.yaml (or merge Dependabot's PR), `pnpm install`, then run
// `pnpm d2:pin` and commit. test/d2-pin.test.ts fails until the two agree.
import { readFileSync, writeFileSync } from "node:fs"

export function lockfilePin(lockfile) {
  const m = /\n {2}'@d2lang\/d2@([^']+)':\n {4}resolution: \{integrity: (sha512-[^}\s]+)\}/.exec(
    lockfile,
  )
  if (!m) throw new Error("No @d2lang/d2 resolution in pnpm-lock.yaml")
  const [, version, integrity] = m
  return {
    version,
    tarball: `https://registry.npmjs.org/@d2lang/d2/-/d2-${version}.tgz`,
    integrity,
  }
}

export function pinSource(pin) {
  return `// Generated by \`pnpm d2:pin\` from pnpm-lock.yaml; do not edit by hand.

/** The D2.js release the action downloads, and the checksum it must match. */
export const D2_PIN = {
  version: "${pin.version}",
  tarball: "${pin.tarball}",
  integrity: "${pin.integrity}",
} as const
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const root = new URL("../", import.meta.url)
  const pin = lockfilePin(readFileSync(new URL("pnpm-lock.yaml", root), "utf8"))
  writeFileSync(new URL("src/d2-pin.ts", root), pinSource(pin))
  console.log(`Pinned @d2lang/d2 ${pin.version} (${pin.integrity.slice(0, 20)}…)`)
}
